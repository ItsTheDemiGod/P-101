# logical operators 

# and - returns true if both are true else false 
print("--and operator--")
print(True and True)
print(True and False)
print(False and False)

# or - returns true if either is true 
print("--Or operator--")
print(True or True)
print(True or False)
print(False or False)


# not opertor 
print("--not operator--")
print(not True)
print(not False)