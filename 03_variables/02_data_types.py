# the following are the data types in python:
# String : it is a sequence of character enclosed within " " , '' 
# Integer : it is a whole number , positive or negative , without decimals , of unlimited length .
# Float : it is a number , positive or negative , containing one or more decimals .
# Boolean : it is a data type that can have only two values : True or False .
# collections :
#1. list[] : it is a collection which is ordered and changeable . allows duplicate members .
#2. tuple() : it is a collection which is ordered and unchangeable . allows duplicate members .
#3. set{} : it is a collection which is unordered and unindexed . no duplicate members    
#4. dictionary{key:value} : it is a collection which is unordered , changeable and indexed . no duplicate members . it contains key value pairs . key value can be of any data type but the key must be unique and immutable .


