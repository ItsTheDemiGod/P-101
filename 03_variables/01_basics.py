# 1. variable name can only start with a letter or an underscore , it cannot start with a number or any speicial character . 
#2. varibles can contain letters , numbers and underscores but cannot contain any special characters or spaces . 
#3. variables are case sensitive which means that the name and Name are two different variables . 
#4. we cannot use any reserved keywords of python as variable name ( if , else , print , for , etc ) . 



