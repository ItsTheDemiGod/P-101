# what is variables in python?
# variables are used to store data in python , think of it as some containers where we store certain values . we store them so that we can use them or manipulate them later in our code .
# these containers have a name and a value/address associated with them with the help of which it can be accessed later in the code.
# variabbles are created the moment we assign a value to them and they can be reassigned to a new value at any point in the code .

name = "string" # it is a string variable 
char  = '@' # it is a special character 
age  = 18 # it is a integer variable 
cgpa = 9.5 # it is a float
is_student = True # it is a boolean variable 


# python is a dynamically typed language which means that we dont have to exlicitly declare the data type of a variable while creating it . python automatically assigns the data type to the variable based on the value assigned to it . where as C is a statically typed language where we have to state which type of variable we are creating .


