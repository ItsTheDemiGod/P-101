# escape line sequence are used to represent special characters in a strin . 

# common escape sequences in python are :
# \n : newline character
# \t : tab character
# \" : double quote character
# \' : single quote character
# \\ : backslash character

# there are more but for right now well only see this much 



# \n : newline character
print(" hello world \n this is demian \n i am learning python")

# \t : tab character
print("Hello\tWorld")

# \" : double quote character
print("hello \"world\"")

# \' : single quote character
print('hello \'world\'')

